// Create 4 functions as specified

// more: takes 1 argument and adds 1
function more(x) {
  return x + 1;
}

// less: takes 1 argument and subtracts 1
function less(x) {
  return x - 1;
}

// add: takes 2 arguments and adds them together
function add(a, b) {
  return a + b;
}

// sub: takes 2 arguments and subtracts second from first
function sub(a, b) {
  return a - b;
}

